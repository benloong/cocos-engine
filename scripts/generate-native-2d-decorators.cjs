/* Generate only the native 2D asset metadata owned by this repository. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const ROOT = path.resolve(__dirname, '..');
const ASSETS = [
    ['font', 'Font'], ['ttf-font', 'TTFFont'], ['bitmap-font', 'BitmapFont'],
    ['label-atlas', 'LabelAtlas'], ['sprite-atlas', 'SpriteAtlas'], ['sprite-frame', 'SpriteFrame'],
];
const OUTPUT = 'cocos/native-binding/decorators-2d.generated.ts';
function decorators(node) { return ts.canHaveDecorators(node) ? ts.getDecorators(node) || [] : []; }
function literal(expression, source) {
    if (!expression) return 'undefined';
    if (ts.isStringLiteral(expression) || ts.isNumericLiteral(expression)
        || [ts.SyntaxKind.NullKeyword, ts.SyntaxKind.TrueKeyword, ts.SyntaxKind.FalseKeyword].includes(expression.kind)) return expression.getText(source);
    if (ts.isPrefixUnaryExpression(expression) && [ts.SyntaxKind.MinusToken, ts.SyntaxKind.PlusToken].includes(expression.operator)
        && ts.isNumericLiteral(expression.operand)) return expression.getText(source);
    if (ts.isCallExpression(expression) && expression.expression.getText(source) === 'js.createMap' && expression.arguments.length === 0) return 'js.createMap()';
    throw new Error(`Unsupported metadata initializer: ${expression.getText(source)}`);
}
function generateClass(text, file, className) {
    const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);
    if (source.parseDiagnostics.length) throw new Error(`Invalid TypeScript: ${file}`);
    const declaration = source.statements.find(node => ts.isClassDeclaration(node) && node.name?.text === className);
    if (!declaration) throw new Error(`${file}: missing ${className}`);
    const context = new Set([className]);
    const statements = [];
    const emit = (decorator, member) => {
        const expr = decorator.expression;
        const call = ts.isCallExpression(expr) ? expr : null;
        const name = (call ? call.expression : expr).getText(source);
        if (!['ccclass', 'serializable', 'editable', 'type', 'string', 'override'].includes(name)) throw new Error(`${file}: unsupported decorator ${name}`);
        let invocation = `$.${name}`;
        if (call) {
            if (name === 'type') {
                if (call.arguments.length !== 1 || !ts.isIdentifier(call.arguments[0])) throw new Error(`${file}: unsupported type decorator`);
                context.add(call.arguments[0].text);
            } else if (name !== 'ccclass') throw new Error(`${file}: unsupported decorator call ${name}`);
            invocation += `(${call.arguments.map(arg => name === 'type' ? arg.getText(source) : literal(arg, source)).join(', ')})`;
        }
        if (!member) {
            if (name !== 'ccclass') throw new Error(`${file}: unsupported class decorator ${name}`);
            statements.push(`    apply(() => { ${invocation}(${className}); }, '${name}', null);`);
            return;
        }
        if (name === 'ccclass' || !ts.isIdentifier(member.name)) throw new Error(`${file}: unsupported member decorator`);
        const key = member.name.text;
        const descriptor = ts.isPropertyDeclaration(member)
            ? `() => ${literal(member.initializer, source)}`
            : `Object.getOwnPropertyDescriptor(${className}.prototype, '${key}')`;
        statements.push(`    apply(() => { ${invocation}(${className}.prototype, '${key}', ${descriptor}); }, '${name}', '${key}');`);
    };
    for (const member of declaration.members) {
        for (const decorator of decorators(member).slice().reverse()) emit(decorator, member);
    }
    for (const decorator of decorators(declaration).slice().reverse()) emit(decorator);
    if (!statements.some(s => s.includes("'ccclass'"))) throw new Error(`${file}: missing ccclass decorator`);
    const names = [...context];
    return `export function patch_cc_${className} ({ ${names.join(', ')} }: { ${names.map(n => n + ': any').join('; ')} }, apply = defaultExec) {\n${statements.join('\n')}\n}\n`;
}
function generate(root = ROOT) {
    const classes = ASSETS.map(([name, klass]) => {
        const file = `cocos/2d/assets/${name}.ts`;
        return generateClass(fs.readFileSync(path.join(root, file), 'utf8'), file, klass);
    });
    return `/* Generated by scripts/generate-native-2d-decorators.cjs. Do not edit. */\n\nimport { _decorator as $, js } from '../core';\n\nconst defaultExec = (cb: () => void, decorator?: string, attr?: string | null): void => { cb(); };\n\n${classes.join('\n')}`;
}
if (require.main === module) {
    const generated = generate();
    const destination = path.join(ROOT, OUTPUT);
    if (process.argv.includes('--check')) {
        if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8').replace(/\r\n/g, '\n') !== generated) {
            console.error(`${OUTPUT} is stale; run node scripts/generate-native-2d-decorators.cjs`);
            process.exitCode = 1;
        } else console.log(`Native 2D metadata: ${ASSETS.length} classes verified`);
    } else {
        fs.writeFileSync(destination, generated);
        console.log(OUTPUT);
    }
}
module.exports = { generate, generateClass, ASSETS, OUTPUT };
